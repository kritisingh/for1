/**
 * Optimizes an image URL for high reliability and speed.
 * Routes Wikimedia images through wsrv.nl Cloudflare CDN cache to prevent 429 rate limits,
 * bypass hotlinking restrictions, and deliver fast WebP images.
 */
export function getOptimizedPhotoUrl(rawUrl, width = 500) {
  if (!rawUrl) return null;
  if (rawUrl.includes('wikimedia.org')) {
    const clean = rawUrl.replace(/^https?:\/\//, '');
    return `https://wsrv.nl/?url=${encodeURIComponent(clean)}&w=${width}&output=webp`;
  }
  return rawUrl;
}

/**
 * Helper to get a real car photo object for any given season year
 */
export function getRealCarForYear(year) {
  let car = REAL_CAR_PHOTOS[year];
  if (!car) {
    const availableYears = Object.keys(REAL_CAR_PHOTOS).map(Number).sort((a, b) => b - a);
    const closest = availableYears.find(y => y <= year) || 1950;
    car = REAL_CAR_PHOTOS[closest];
  }
  if (!car) return null;
  
  const rawPhoto = car.photo || car.realPhoto;
  return {
    ...car,
    photo: getOptimizedPhotoUrl(rawPhoto),
    optimizedPhoto: getOptimizedPhotoUrl(rawPhoto),
    rawPhoto
  };
}

